// Regenerates, or checks, the shipped assets from the pinned inputs.
//
//   dart run tool/generate.dart            write assets/ from tool/inputs.lock
//   dart run tool/generate.dart check      fail unless assets/ is what that
//                                          would write (the CI gate)
//   dart run tool/generate.dart lock <emoji-version> <cldr-tag>
//       [--shortcodes-ref=<tag>] [locale...]
//                                          re-pin to other versions (and
//                                          emoji-toolkit tag and locales;
//                                          default: the current ones)
//
// Inputs are downloaded once into tool/.cache (untracked) and verified
// against the SHA-256 in tool/inputs.lock on every run. Nothing downloaded is
// ever executed or imported; the files are only read as text.
import 'dart:convert';
import 'dart:io';

import 'package:crypto/crypto.dart';
import 'package:emoji_catalog_pack/generator.dart';

const int _fetchAttempts = 3;

Future<void> main(List<String> args) async {
  final root = File.fromUri(Platform.script).parent.parent;
  final lockFile = File('${root.path}/tool/inputs.lock');
  final cache = Directory(
    Platform.environment['EMOJI_CATALOG_PACK_CACHE'] ??
        '${root.path}/tool/.cache',
  );
  final command = args.isEmpty ? 'generate' : args.first;
  try {
    switch (command) {
      case 'generate':
        await _write(root, await _generate(lockFile, cache));
      case 'check':
        await _check(root, await _generate(lockFile, cache));
      case 'lock':
        await _lock(lockFile, cache, args.skip(1).toList());
      default:
        throw ArgumentError('Unknown command: $command.');
    }
  } on Exception catch (error) {
    stderr.writeln('emoji_catalog_pack: $error');
    exitCode = 1;
  }
}

Future<Map<String, String>> _generate(File lockFile, Directory cache) async {
  final lock = InputsLock.parse(await lockFile.readAsString());
  final texts = <String, String>{};
  for (final input in lock.inputs) {
    final bytes = await _verified(input.source, input.sha256, cache);
    // Strict UTF-8: an input that is not text must fail, not be mangled.
    texts[input.name] = utf8.decode(bytes);
  }
  return AssetGenerator.generate(lock: lock, readInput: (name) => texts[name]!);
}

Future<void> _write(Directory root, Map<String, String> assets) async {
  final stale = _existing(root).where((path) => !assets.containsKey(path));
  for (final path in stale) {
    File('${root.path}/$path').deleteSync();
  }
  for (final entry in assets.entries) {
    final file = File('${root.path}/${entry.key}');
    await file.parent.create(recursive: true);
    await file.writeAsString(entry.value);
  }
  stdout.writeln('Wrote ${assets.length} assets.');
}

Future<void> _check(Directory root, Map<String, String> assets) async {
  final problems = <String>[];
  for (final entry in assets.entries) {
    final file = File('${root.path}/${entry.key}');
    if (!file.existsSync()) {
      problems.add('missing: ${entry.key}');
    } else if (await file.readAsString() != entry.value) {
      problems.add('differs from the pinned inputs: ${entry.key}');
    }
  }
  for (final path in _existing(root).where((p) => !assets.containsKey(p))) {
    problems.add('not generated by the pinned inputs: $path');
  }
  if (problems.isNotEmpty) {
    throw _Failure(
      'assets/ is not reproducible from tool/inputs.lock:\n'
      '  ${problems.join('\n  ')}\n'
      'Run `dart run tool/generate.dart` and commit the result.',
    );
  }
  stdout.writeln('assets/ matches tool/inputs.lock (${assets.length} files).');
}

Iterable<String> _existing(Directory root) {
  final assets = Directory('${root.path}/assets');
  if (!assets.existsSync()) return const [];
  return [
    for (final file in assets.listSync(recursive: true).whereType<File>())
      file.path.substring(root.path.length + 1),
  ]..sort();
}

Never _noLocales() =>
    throw ArgumentError('No inputs.lock to take the locales from; list them.');

Never _noShortcodesRef() => throw ArgumentError(
  'No inputs.lock to take the emoji-toolkit tag from; '
  'pass --shortcodes-ref=<tag>.',
);

const String _shortcodesFlag = '--shortcodes-ref=';

Future<void> _lock(File lockFile, Directory cache, List<String> all) async {
  final current = lockFile.existsSync()
      ? InputsLock.parse(await lockFile.readAsString())
      : null;
  final flags = all.where((arg) => arg.startsWith(_shortcodesFlag));
  final args = all.where((arg) => !arg.startsWith(_shortcodesFlag)).toList();
  final plan = args.length >= 2
      ? InputsPlan(
          emojiVersion: args[0],
          cldrTag: args[1],
          shortcodesRef: flags.isNotEmpty
              ? flags.last.substring(_shortcodesFlag.length)
              : current?.shortcodesRef ?? _noShortcodesRef(),
          locales: args.length > 2
              ? args.sublist(2)
              : current?.locales ?? _noLocales(),
        )
      : throw ArgumentError(
          'lock needs <emoji-version> <cldr-tag> '
          '[--shortcodes-ref=<tag>] [locale...]',
        );
  final hashes = <String, String>{};
  for (final source in plan.sources) {
    final bytes = await _download(source);
    hashes[source.name] = sha256.convert(bytes).toString();
    final file = File('${cache.path}/${source.name}');
    await file.parent.create(recursive: true);
    await file.writeAsBytes(bytes);
  }
  final lock = InputsLock.pin(plan, (source) => hashes[source.name]!);
  await lockFile.writeAsString(lock.encode());
  stdout.writeln('Pinned ${lock.inputs.length} inputs.');
}

/// The bytes of [source], from the cache when they match [sha256], else
/// downloaded; throws when what the URL serves does not match the pin.
Future<List<int>> _verified(
  InputSource source,
  String expected,
  Directory cache,
) async {
  final file = File('${cache.path}/${source.name}');
  if (file.existsSync()) {
    final cached = await file.readAsBytes();
    if (sha256.convert(cached).toString() == expected) return cached;
  }
  final bytes = await _download(source);
  final actual = sha256.convert(bytes).toString();
  if (actual != expected) {
    throw _Failure(
      '${source.url} serves $actual, the lock pins $expected. '
      'Re-pin with `dart run tool/generate.dart lock ...` if that is intended.',
    );
  }
  await file.parent.create(recursive: true);
  await file.writeAsBytes(bytes);
  return bytes;
}

Future<List<int>> _download(InputSource source) async {
  final client = HttpClient();
  try {
    for (var attempt = 1; ; attempt++) {
      try {
        final request = await client.getUrl(Uri.parse(source.url));
        final response = await request.close();
        if (response.statusCode != HttpStatus.ok) {
          throw HttpException('HTTP ${response.statusCode}', uri: request.uri);
        }
        return await response.fold<List<int>>(
          [],
          (all, chunk) => all..addAll(chunk),
        );
      } on IOException {
        if (attempt == _fetchAttempts) rethrow;
        await Future<void>.delayed(Duration(seconds: attempt));
      }
    }
  } finally {
    client.close();
  }
}

/// A failed gate or pin, reported as a message without a stack trace.
class _Failure implements Exception {
  _Failure(this.message);

  final String message;

  @override
  String toString() => message;
}
